// Row() has to key on whether the *model* field is a pointer, not on whether
// the column is nullable. The two agree everywhere except the slice-typed
// columns: a nullable bytea stays []byte and an array stays []T either way,
// because a nil slice is already how a slice says NULL.
//
// Keying on nullability assigned the body field straight across for those,
// which is a *[]byte going into a []byte — generated code that does not
// compile. jsonb was in this bucket until a nullable jsonb became a pointer,
// which is why the bug outlived the column that first showed it.
func TestCreateBodyAssignsSliceColumnsThroughTheDeref(t *testing.T) {
	r := schema.NewRegistry()
	r.Table("documents",
		schema.UUIDv7("id").PrimaryKey(),
		schema.JSON("attachment_ids").Nullable(),
		schema.Bytes("thumbnail").Nullable(),
		schema.Text("tags").Array().Nullable(),
	).Expose(schema.REST{Ops: schema.OpCreate})
	rest := generate(t, r)["rest_gen.go"]

	// Create-only is the shape that exposed this: the patch body imports
	// encoding/json for its presence tracking, so every resource exposed for
	// update got the import by accident and only a create-only one named
	// json.RawMessage without it.
	if !contains(rest, `"encoding/json"`) {
		t.Errorf("rest names json.RawMessage without importing it:\n%s", rest)
	}

	for _, want := range []string{
		// The body is a pointer wherever the model is not, so the assignment
		// has to dereference it.
		`Thumbnail *[]byte`,
		"if c.Thumbnail != nil {\nrow.Thumbnail = *c.Thumbnail\n}",
		`Tags *[]string`,
		"if c.Tags != nil {\nrow.Tags = *c.Tags\n}",
		// A nullable jsonb is a pointer in the model, so body and model agree
		// and absent and null both mean NULL. No deref.
		`AttachmentIds *json.RawMessage`,
		"row.AttachmentIds = c.AttachmentIds",
	} {
		if !contains(rest, want) {
			t.Errorf("rest missing %q:\n%s", want, rest)
		}
	}
	// The failure this guards is an assignment across the pointer boundary.
	// Spelled out because the deref assertions above would still pass if a
	// second, wrong assignment were emitted alongside them.
	for _, bad := range []string{
		"row.Thumbnail = c.Thumbnail",
		"row.Tags = c.Tags",
		"row.AttachmentIds = *c.AttachmentIds",
	} {
		if contains(rest, bad) {
			t.Errorf("rest assigns across the pointer boundary %q:\n%s", bad, rest)
		}
	}
}

// The mirror of TestColumnsImportsWhatItNames, in the direction the rest
// emitter got wrong: an import for a type the file never names.
//
// The import set was derived from the create field list of every exposed
// table, without asking whether a create body was emitted for it. A resource
// exposed for reads only emits no body at all — the whole file is the Register
// function, which names nothing but the model types — so a timestamp column on
// such a table produced a rest_gen.go importing "time" with no time.Time in it.
//
// Invisible to codegen for the same reason the missing-import bugs were:
// format.Source parses without type-checking, and an unused import is valid Go
// source that only fails at the consumer's compiler. TestGeneratedGoCompiles is
// the general guard; this is the case that prompted it.
func TestRestImportsNothingItDoesNotName(t *testing.T) {
	// The fixture is already this shape — exposed for OpList, with a nullable
	// timestamp — and generating from it is what produced the file that did
	// not compile.
	src := generate(t, fixture())["rest_gen.go"]

	if contains(src, `"time"`) {
		t.Errorf("a resource that emits no body imports time:\n%s", src)
	}

	// The same defect through the other import the patch body earns. errors is
	// named only where Changes() refuses an explicit null, which is only for a
	// column that cannot hold one — but it was added for the patch body's mere
	// existence, so a table whose every patchable column is nullable imported
	// it and never used it.
	nullable := schema.NewRegistry()
	nullable.Table("posts",
		schema.UUIDv7("id").PrimaryKey(),
		schema.Text("title").Nullable(),
	).Expose(schema.REST{Ops: schema.OpUpdate})
	src = generate(t, nullable)["rest_gen.go"]

	if contains(src, `"errors"`) {
		t.Errorf("an all-nullable patch body imports errors:\n%s", src)
	}

	// And the import is narrowed, not removed: one non-nullable column brings
	// the rejection back, and with it the import.
	required := schema.NewRegistry()
	required.Table("posts",
		schema.UUIDv7("id").PrimaryKey(),
		schema.Text("title"),
	).Expose(schema.REST{Ops: schema.OpUpdate})
	src = generate(t, required)["rest_gen.go"]

	for _, want := range []string{
		`"errors"`,
		`errors.New("title is not nullable and cannot be set to null")`,
	} {
		if !contains(src, want) {
			t.Errorf("a non-nullable patch column is missing %q:\n%s", want, src)
		}
	}
}

func TestGeneratedColumns(t *testing.T) {
	cols := generate(t, fixture())["columns_gen.go"]

	for _, want := range []string{
		"var BlogEntryCols = blogEntryColumns{",
		"Title sqlb.TextCol[string]",       // text gets the pattern operators
		"Status sqlb.Col[BlogEntryStatus]", // enum keeps its type
		"ViewCount sqlb.Col[int64]",        // an integer does not get them
		"PublishedAt sqlb.Col[time.Time]",  // nullable compares to the base type
		`sqlb.TextColumn[string]("title")`,
	} {
		if !contains(cols, want) {
			t.Errorf("columns missing %q:\n%s", want, cols)
		}
	}
	// A hidden column must not be reachable from a predicate: it has no entry
	// in the column set, so no comparison against it compiles.
	//
	// It does still get a setter. Hidden gates reads — filters, sorts,
	// projections and responses — not writes, because a password hash has to
	// stay writable from Go. The facade is the read surface; the update
	// wrapper is the write surface.
	set := cols[strings.Index(cols, "type blogEntryColumns"):strings.Index(cols, "type BlogEntryUpdate")]
	if contains(set, "Secret") || contains(set, `"secret"`) {
		t.Errorf("a hidden column leaked into the column set:\n%s", set)
	}
	if !contains(cols, "SetSecret(v string)") {
		t.Error("a hidden column should still be writable from Go")
	}
}

func TestGeneratedUpdateSkipsOnlyThePrimaryKey(t *testing.T) {
	cols := generate(t, fixture())["columns_gen.go"]

	if !contains(cols, "func (u *BlogEntryUpdate) SetTitle(v string) *BlogEntryUpdate {") {
		t.Errorf("expected a typed setter for title:\n%s", cols)
	}
	if !contains(cols, "SetStatus(v BlogEntryStatus)") {
		t.Error("the enum setter should take the enum type")
	}
	// A ReadOnly column gets one too. ReadOnly is a REST-boundary rule, and
	// the boundary is defended there — the column is absent from the request
	// bodies. Go through the query engine is trusted, so leaving it out only
	// meant that the code which is the sole writer of view_count was the one
	// code that had to write it untyped.
	if !contains(cols, "SetViewCount(v int64)") {
		t.Errorf("a read-only column should still be writable typed from Go:\n%s", cols)
	}
	// The primary key addresses the row rather than being part of what an
	// update writes. Stmt() is the way to mean it.
	if contains(cols, "SetID(") {
		t.Error("the primary key must not get a setter")
	}
}

