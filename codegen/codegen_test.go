// A nullable jsonb column is a pointer for the same reason every other
// nullable column is, and unlike the bytea sitting next to it here.
//
// Both map onto a slice of bytes, which is why the two were once treated alike
// and a nullable jsonb was emitted bare. Only bytea earns it: nil is what a
// []byte *is* when it is absent, whereas json.RawMessage is a document type,
// and emitting it bare left a nullable jsonb as the one column whose generated
// type did not state that it could be NULL.
//
// Under database/sql — sqlb's executor until it took pgx as a dependency — the
// bare form could not even be read: convertAssign resolves a destination by
// concrete type, and a named type over []byte matches no case, so a NULL failed
// with "unsupported Scan, storing driver.Value type <nil>". pgx has no such gap,
// so this is no longer load-bearing for sqlb's own reads. It stays load-bearing
// for the generated struct, which is a plain Go type other code scans too.
func TestNullableJSONIsAPointer(t *testing.T) {
	r := schema.NewRegistry()
	r.Table("documents",
		schema.UUIDv7("id").PrimaryKey(),
		schema.JSON("meta"),
		schema.JSON("attachment_ids").Nullable(),
		schema.Bytes("thumbnail").Nullable(),
	)
	models := generate(t, r)["models_gen.go"]

	for _, want := range []string{
		`Meta json.RawMessage`,
		// AttachmentIds, not AttachmentIDs: the initialism table carries "id"
		// and not its plural. Unrelated to what this test is about, and
		// asserted as it actually renders rather than as it reads best.
		`AttachmentIds *json.RawMessage`,
		`Thumbnail []byte`, // a nil slice is already how a bytea says NULL
		// The pointer must not cost the import: the import set is keyed off
		// the rendered Go type, so a type it does not recognise silently
		// produces a model that does not compile.
		`"encoding/json"`,
	} {
		if !contains(models, want) {
			t.Errorf("models missing %q:\n%s", want, models)
		}
	}
}

// The columns file needs `encoding/json` for the same reason the models file
// does, and used to go without it: the import set here was a bare check for
// time.Time, so a jsonb column produced a columns file naming json.RawMessage
// with nothing importing it.
//
// gofmt does not catch this. codegen runs format.Source over every file, which
// parses but does not type-check, so a missing import is valid Go source that
// only fails at the consumer's compiler — which is why the models emitter was
// fixed for this and the columns emitter was not noticed.
func TestColumnsImportsWhatItNames(t *testing.T) {
	r := schema.NewRegistry()
	r.Table("documents",
		schema.UUIDv7("id").PrimaryKey(),
		schema.JSON("meta"),
		schema.JSON("attachment_ids").Nullable(),
	)
	cols := generate(t, r)["columns_gen.go"]

	if !contains(cols, `"encoding/json"`) {
		t.Errorf("columns names json.RawMessage without importing it:\n%s", cols)
	}
	for _, want := range []string{
		// Both spellings collapse to the base type here, the same way a
		// nullable timestamp compares as time.Time: a column is what you
		// compare against, and NULL is not a value you write in a predicate.
		"Meta sqlb.Col[json.RawMessage]",
		"AttachmentIds sqlb.Col[json.RawMessage]",
		"SetMeta(v json.RawMessage)",
	} {
		if !contains(cols, want) {
			t.Errorf("columns missing %q:\n%s", want, cols)
		}
	}
}

// The columns file has two halves that disagree about hidden columns, and only
// one of them was accounted for.
//
// The facade omits a hidden column so that a predicate against one does not
// compile. The typed update deliberately keeps it — writing an embedding from
// Go is the whole point of the one hidden column this repository has — so a
// hidden timestamp is set by a Set…(v time.Time) in a file whose import set was
// built from the facade's columns alone.
//
// It survived because the hidden column it was written for is the vector one,
// whose import is sqlb and is there unconditionally.
func TestColumnsImportsWhatTheTypedUpdateNames(t *testing.T) {
	r := schema.NewRegistry()
	r.Table("users",
		schema.UUIDv7("id").PrimaryKey(),
		schema.Text("name"),
		schema.Timestamp("last_seen_at").Hidden(),
		schema.JSON("audit").Hidden(),
	)
	cols := generate(t, r)["columns_gen.go"]

	for _, want := range []string{
		// The setters exist, which is what makes the imports necessary.
		"func (u *UserUpdate) SetLastSeenAt(v time.Time)",
		"func (u *UserUpdate) SetAudit(v json.RawMessage)",
		`"time"`,
		`"encoding/json"`,
	} {
		if !contains(cols, want) {
			t.Errorf("columns missing %q:\n%s", want, cols)
		}
	}
	// And the facade still omits them, so this is an import fix and not a
	// hidden column becoming queryable.
	facade := cols[strings.Index(cols, "type userColumns struct {"):strings.Index(cols, "type UserUpdate struct {")]
	for _, forbidden := range []string{"LastSeenAt", "Audit"} {
		if contains(facade, forbidden) {
			t.Errorf("a hidden column reached the typed facade (%s):\n%s", forbidden, facade)
		}
	}
}

