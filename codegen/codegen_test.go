// A generated body reports which optional columns the request carried, so that
// a sent zero is written rather than being read as "absent, use the default".
//
// The shape the report is for is Bool(...).Default(Value(true)) — false is both
// the zero and the interesting state — but the emitter does not special-case
// bools: any optional column has the same ambiguity, and the pointer that
// resolves it is already there (#314).
func TestGeneratedCreateBodyReportsTheColumnsTheRequestCarried(t *testing.T) {
	src := generate(t, restFixture())["rest_gen.go"]

	for _, want := range []string{
		"func (c PostCreate) Explicit() []string {",
		"\tif c.Status != nil {\n\t\tcols = append(cols, \"status\")\n\t}",
	} {
		if !contains(src, want) {
			t.Errorf("create body missing %q:\n%s", want, src)
		}
	}
	explicit := src[strings.Index(src, "func (c PostCreate) Explicit()"):]
	explicit = explicit[:strings.Index(explicit, "\n}\n")]
	// A required column was always sent, so there is nothing to report about
	// it; naming it would be noise that also has to stay correct.
	if contains(explicit, `"title"`) {
		t.Errorf("a required column has no absent case to report:\n%s", explicit)
	}
	// A nullable column's body field is the model's pointer, so absent and
	// null are the same request and neither is a zero to write.
	if contains(explicit, `"published_at"`) {
		t.Errorf("a pointer-modelled column cannot report what it cannot tell apart:\n%s", explicit)
	}
}

// An enum column types as a string alias, which Huma documents as a plain
// string — so without the tag an invalid value passed validation, reached the
// INSERT and returned whatever the database said. The generated TypeScript
// client and CLI both enforce the value set, which left the one participant
// that has to as the only one that did not.
func TestGeneratedBodiesConstrainEnumValues(t *testing.T) {
	src := generate(t, restFixture())["rest_gen.go"]

	for _, want := range []string{
		`Status *PostStatus ` + "`" + `json:"status,omitempty" enum:"draft,published"`,
	} {
		if !contains(src, want) {
			t.Errorf("body missing the enum constraint %q:\n%s", want, src)
		}
	}
	// Both bodies, not just the create one: a patch can set a column too.
	patch := src[strings.Index(src, "type PostPatch struct {"):]
	if !contains(patch, `enum:"draft,published"`) {
		t.Errorf("patch body does not constrain the enum:\n%s", patch)
	}
	// A non-enum column must not grow the tag.
	if contains(src, `json:"title" enum:`) {
		t.Error("a plain text column should carry no enum constraint")
	}
}

func TestGeneratedPatchBodyDistinguishesAbsentFromNull(t *testing.T) {
	src := generate(t, restFixture())["rest_gen.go"]

	for _, want := range []string{
		"type PostPatch struct {",
		"present map[string]bool",
		"func (u *PostPatch) UnmarshalJSON(data []byte) error",
		"func (u PostPatch) Changes() (map[string]any, error)",
		// A nullable column that was present writes its pointer straight
		// through, so an explicit null becomes NULL.
		`out["published_at"] = u.PublishedAt`,
		// A non-nullable one rejects an explicit null rather than writing a
		// zero value that looks deliberate.
		`errors.New("title is not nullable and cannot be set to null")`,
	} {
		if !contains(src, want) {
			t.Errorf("patch body missing %q:\n%s", want, src)
		}
	}
	// An immutable column is settable once, at create, so it has no place in a
	// patch body at all.
	patch := src[strings.Index(src, "type PostPatch struct {"):strings.Index(src, "func (u *PostPatch) UnmarshalJSON")]
	if contains(patch, "OrgID") {
		t.Errorf("an immutable column should be absent from the patch body:\n%s", patch)
	}
}

func TestGeneratedRegisterMirrorsTheSchemaExposure(t *testing.T) {
	src := generate(t, restFixture())["rest_gen.go"]

	for _, want := range []string{
		"func Register(api huma.API, db sqlb.Executor) error {",
		"rest.Resource[Post, PostCreate, PostPatch](api, db, rest.Options{",
		`Path: "/posts"`,
		`Name: "post"`, // singularised, for operation IDs
		"Ops: rest.OpCreate | rest.OpRead | rest.OpUpdate | rest.OpDelete | rest.OpList",
		"MaxPageSize: 50",
	} {
		if !contains(src, want) {
			t.Errorf("registration missing %q:\n%s", want, src)
		}
	}
	// orgs is not exposed, so it is not mounted.
	if contains(src, "rest.Resource[Org") {
		t.Errorf("an unexposed table should not be mounted:\n%s", src)
	}
}

