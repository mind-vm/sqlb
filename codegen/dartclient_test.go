// A capability a column did not declare has no spelling at all. These are the
// same refusals example/tasks/mobile/lib/refusals.dart asserts against a real
// analyser; this is the cheap version that runs without a Dart toolchain.
func TestDartOffersNoVocabularyForUndeclaredCapabilities(t *testing.T) {
	r := schema.NewRegistry()
	r.Table("posts",
		schema.UUIDv7("id").PrimaryKey(),
		schema.Text("title"), // no capabilities at all
		schema.Int("views").Filterable(),
	).Expose(schema.REST{Ops: schema.OpList})

	src := generateDart(t, r)

	// Filterable and sortable are separate opt-ins, so a filterable column with
	// no .Sortable() must not appear in the sort vocabulary — and a resource
	// whose columns are all unsortable gets no sort enum at all.
	if contains(src, "enum PostSort") {
		t.Errorf("a sort vocabulary was emitted for a schema with no sortable column:\n%s", src)
	}
	where := section(t, src, "class PostWhere {", "\n}")
	if contains(where, "title") {
		t.Errorf("a column that never declared .Filterable() reached the where clause:\n%s", where)
	}
	// It is still selectable: hiding is what Hidden() is for, and a column with
	// no capabilities is still part of the row.
	if !contains(src, "title('title')") {
		t.Errorf("a plain column should still be selectable:\n%s", src)
	}
}

