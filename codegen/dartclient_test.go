// generateDart returns the emitted Dart client.
func generateDart(t *testing.T, r *schema.Registry) string {
	t.Helper()
	dir := t.TempDir()
	files, err := codegen.Generate(codegen.Options{
		Registry: r, Dir: dir, Package: "gen", DartDir: "mobile/lib/api",
	})
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	for _, f := range files {
		if filepath.Ext(f) != ".dart" {
			continue
		}
		b, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	t.Fatal("no Dart was emitted")
	return ""
}

// The row view carries lowerCamelCase members over the wire spelling, which is
// the one decision that goes the other way from the TypeScript client
// (ADR-0031): snake_case members would fail the lowerCamelCase lint in every
// Dart file that touched them, and Dart has to decode a response explicitly
// anyway, so the mapping costs a string constant rather than a runtime layer.
func TestDartRowsAreCamelCasedOverTheWireSpelling(t *testing.T) {
	src := generateDart(t, tsFixture())

	for _, want := range []string{
		"// Code generated by github.com/mind-vm/sqlb. DO NOT EDIT.",
		"class Post extends Row {",
		"static const String table = 'posts';",
		"String get id => _str('id');",
		"String get orgId => _str('org_id');",      // camelCase member, wire name beside it
		"int get viewCount => _int('view_count');", // bigint is an int
		"Compiled to JavaScript this is a double",  // and the loss is silent on one platform only
		"PostStatus get status => _enum('status', PostStatus.byWire);",
		"DateTime? get publishedAt => _timeOrNull('published_at');",
		"enum PostStatus implements WireValue {",
		"draft('draft'),",
	} {
		if !contains(src, want) {
			t.Errorf("row view missing %q:\n%s", want, src)
		}
	}

	// A hidden column has no spelling here at all: not on the row, not in the
	// projection vocabulary, not as a filter. Same guarantee the typed column
	// facade gives Go, carried across the wire.
	if contains(src, "secret") {
		t.Errorf("a hidden column leaked into the client:\n%s", src)
	}
}

// TestDartWriteResultExcludesNeedsColumns is #188's Dart half. A row view
// reads its columns lazily off the raw JSON map, so before this test's fix a
// getter for a Needs column compiled fine on a create/update response and
// then threw MissingColumn the first time something called it — the same
// promise-something-a-write-cannot-answer bug as the TypeScript client, just
// caught at a different moment. computedFixture, shared with
// computed_test.go, carries is_starred with Needs("viewer") and is_overdue
// without it.
func TestDartWriteResultExcludesNeedsColumns(t *testing.T) {
	src := generateDart(t, computedFixture())

	// The read view still offers both — a read has a bind to resolve
	// isStarred with.
	row := section(t, src, "class Project extends Row {", "\n}")
	for _, want := range []string{"bool? get isOverdue", "bool get isStarred"} {
		if !contains(row, want) {
			t.Errorf("read row view is missing %q:\n%s", want, row)
		}
	}

	// The write-result class exists because of the Needs column, and it
	// drops only that getter — isOverdue has no bind problem and stays.
	result := section(t, src, "class ProjectWriteResult extends Row {", "\n}")
	if !contains(result, "bool? get isOverdue") {
		t.Errorf("write result should still offer isOverdue:\n%s", result)
	}
	if contains(result, "isStarred") {
		t.Errorf("write result must not offer isStarred:\n%s", result)
	}

	// create and update return the narrowed class, not the row view a read
	// returns.
	for _, want := range []string{"Future<ProjectWriteResult> createProject(", "Future<ProjectWriteResult> updateProject("} {
		if !contains(src, want) {
			t.Errorf("write transport missing %q:\n%s", want, src)
		}
	}

	// Reads are unaffected: they still return the full row view.
	for _, want := range []string{"Future<Project> getProject(", "Future<Page<Project>> listProjects("} {
		if !contains(src, want) {
			t.Errorf("read transport missing %q:\n%s", want, src)
		}
	}
}

