// Request bodies come off the same column sets the Go bodies use, so the two
// cannot disagree about what a request may write.
func TestDartBodiesFollowTheWriteProtection(t *testing.T) {
	src := generateDart(t, tsFixture())

	create := section(t, src, "class PostCreate {", "\n}")
	if contains(create, "viewCount") {
		t.Errorf("a read-only column reached the create body:\n%s", create)
	}
	if !contains(create, "required this.orgId") || !contains(create, "required this.title") {
		t.Errorf("a column with no default should be required:\n%s", create)
	}
	// status has a default, so omitting it means the database supplies one.
	if !contains(create, "this.status,") || !contains(create, "final PostStatus? status;") {
		t.Errorf("a defaulted column should be optional:\n%s", create)
	}

	patch := section(t, src, "class PostPatch {", "\n}")
	if contains(patch, "void orgId(") {
		t.Errorf("an immutable column reached the patch body:\n%s", patch)
	}
	if !contains(patch, "void title(String value)") {
		t.Errorf("a writable column should have a patch method:\n%s", patch)
	}
	// Nullable is what makes a method accept null, and passing null is what
	// writes NULL. A column left unmentioned is not written at all, which is a
	// distinction a field could not carry.
	if !contains(patch, "void publishedAt(DateTime? value)") {
		t.Errorf("a nullable column's patch method should accept null:\n%s", patch)
	}
}

// A table whose singular collides with a dart:core type takes a Row suffix.
// Declaring `class List` would make every List<T> in the emitted library refer
// to it, and the failure would be a wall of type errors rather than a clash.
func TestDartRenamesARowThatWouldShadowDartCore(t *testing.T) {
	r := schema.NewRegistry()
	r.Table("lists",
		schema.UUIDv7("id").PrimaryKey(),
		schema.Text("name").Sortable(),
	).Expose(schema.REST{Ops: schema.OpRead | schema.OpList})

	src := generateDart(t, r)

	for _, want := range []string{
		"class ListRow extends Row {",
		"Future<Page<ListRow>> listLists(",
		"Future<ListRow> getList(",
		"enum ListColumn implements WireValue {", // the vocabulary keeps the plain name
		"class ListListParams {",
	} {
		if !contains(src, want) {
			t.Errorf("collision handling missing %q:\n%s", want, src)
		}
	}
	if contains(src, "\nclass List extends Row") {
		t.Errorf("a row class shadowed dart:core.List:\n%s", src)
	}
}

// The pager is the layer a phone needs and a schema can supply: a list on a
// small screen loads as it is scrolled, and paging it by offset is the
// arithmetic keyset cursors exist to replace (ADR-0027).
func TestDartEmitsACursorPagerForEveryListableResource(t *testing.T) {
	src := generateDart(t, tsFixture())

	if !contains(src, "CursorPager<Post> postPager(") {
		t.Errorf("no pager for a listable resource:\n%s", src)
	}
	if !contains(src, "params: params.withCursor(cursor)") {
		t.Errorf("the pager should own the cursor:\n%s", src)
	}
	// page and cursor are two answers to where a page starts, so withCursor
	// drops the page number rather than sending both.
	withCursor := section(t, src, "PostListParams withCursor(String? cursor)", ");")
	if contains(withCursor, "page: page") {
		t.Errorf("withCursor kept the page number:\n%s", withCursor)
	}
}

// #302: withCursor fused "=> TypeName(" onto the signature line
// unconditionally, so a long enough table name pushed the line past dartWidth
// and dart format rewrote it — breaking after "=>" instead, one indent level
// deeper, the same way dartLine already handles every other member in this
// file. withCursor now makes that same call.
func TestDartWithCursorWrapsALongSignature(t *testing.T) {
	r := schema.NewRegistry()
	r.Table("pairing_sessions",
		schema.UUIDv7("id").PrimaryKey(),
		schema.Text("name").Sortable(),
	).Expose(schema.REST{Ops: schema.OpList})

	src := generateDart(t, r)
	withCursor := section(t, src,
		"PairingSessionListParams withCursor(String? cursor)", ");")

	if !contains(withCursor, "PairingSessionListParams withCursor(String? cursor) =>\n") {
		t.Errorf("signature should break after '=>' once it would exceed %d columns:\n%s", 80, withCursor)
	}
	if !contains(withCursor, "\n      PairingSessionListParams(\n") {
		t.Errorf("the constructor call should start on its own line, indented one level deeper:\n%s", withCursor)
	}
	for line := range strings.SplitSeq(withCursor, "\n") {
		if len(line) > 80 {
			t.Errorf("line exceeds dart format's 80-column width, so dart format would rewrite it:\n%q", line)
		}
	}
}

