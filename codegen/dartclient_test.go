// The Dart is part of the committed output, so the staleness gate has to see
// it — otherwise the client silently describes a schema the server no longer
// has.
func TestCheckSeesTheDart(t *testing.T) {
	dir := t.TempDir()
	opts := codegen.Options{Registry: tsFixture(), Dir: dir, Package: "gen", DartDir: "mobile/lib/api"}
	if _, err := codegen.Generate(opts); err != nil {
		t.Fatal(err)
	}
	if stale, err := codegen.Check(opts); err != nil || len(stale) > 0 {
		t.Fatalf("freshly generated output should be current: %v %v", stale, err)
	}

	path := filepath.Join(dir, "mobile", "lib", "api", "client.gen.dart")
	if err := os.WriteFile(path, []byte("// edited by hand\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	stale, err := codegen.Check(opts)
	if err != nil {
		t.Fatal(err)
	}
	if len(stale) != 1 || !strings.Contains(stale[0], "client.gen.dart") {
		t.Errorf("an edited client should be reported stale, got %v", stale)
	}
}

// Column types map onto what the *wire* carries, not onto what the SQL type is
// called. All three time types are a time.Time in the row struct and therefore
// RFC 3339 in the response, so a date column does not arrive as YYYY-MM-DD —
// which the Dart type cannot say and the doc comment therefore does.
func TestDartTimeColumnsFollowTheWireAndNotTheSQLType(t *testing.T) {
	r := schema.NewRegistry()
	r.Table("events",
		schema.UUIDv7("id").PrimaryKey(),
		schema.Timestamp("starts_at"),
		schema.Date("held_on"),
		schema.Time("doors_open"),
		schema.Bytes("poster").Nullable(),
		schema.JSON("meta"),
		schema.Float("rating"),
	)

	src := generateDart(t, r)

	for _, want := range []string{
		"DateTime get startsAt => _time('starts_at');",
		"DateTime get heldOn => _time('held_on');",
		"DateTime get doorsOpen => _time('doors_open');",
		"It arrives as a timestamp at midnight UTC",
		"String? get poster => _strOrNull('poster');", // bytea is base64
		"Base64, as JSON carries bytes.",
		"Object get meta => _any('meta');",
		// A JSON number decodes as int when it is whole, so a double column has
		// to go through num — the trap a plain `as double` walks into.
		"double get rating => _double('rating');",
	} {
		if !contains(src, want) {
			t.Errorf("column mapping missing %q:\n%s", want, src)
		}
	}
}

