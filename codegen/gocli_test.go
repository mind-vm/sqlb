// cliFixture is tsFixture with a jsonb column and a nullable text column, which
// are the two write flags that need a spelling of their own: one carries a
// document rather than a string, and one has to be settable back to null.
func cliFixture() *schema.Registry {
	r := schema.NewRegistry()
	org := r.Table("orgs",
		schema.UUIDv7("id").PrimaryKey(),
		schema.Text("name").Sortable(),
	).Expose(schema.REST{Ops: schema.OpRead | schema.OpList})

	r.Table("posts",
		schema.UUIDv7("id").PrimaryKey(),
		schema.Ref("org", org).OnDelete(schema.Cascade).Immutable().Filterable().
			Expandable().Inverse("posts").InverseExpandable(),
		schema.Text("title").Searchable().Sortable(),
		schema.Text("subtitle").Nullable(),
		schema.Enum("status", "draft", "published").Default(schema.Value("draft")).Filterable(),
		schema.BigInt("view_count").ReadOnly().Filterable(),
		schema.Timestamp("published_at").Nullable().Filterable().Sortable(),
		schema.JSON("meta").Nullable(),
		schema.Text("secret").Hidden(),
	).Expose(schema.REST{Ops: schema.CRUD | schema.OpList, MaxPageSize: 50})
	return r
}

// generateCLI returns the emitted command tree.
func generateCLI(t *testing.T, r *schema.Registry) string {
	t.Helper()
	dir := t.TempDir()
	files, err := codegen.Generate(codegen.Options{
		Registry: r, Dir: dir, Package: "gen",
		CLIDir: "cli", CLIName: "blogctl",
		ClientImportPath: "example.com/app/cli/client",
	})
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	for _, f := range files {
		if filepath.Base(f) != "cli_gen.go" {
			continue
		}
		b, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	t.Fatal("no CLI was emitted")
	return ""
}

// usage returns the help text registered for one filter flag, found by the
// variable it writes into. Anchoring on the variable rather than on the flag
// name is what keeps the assertion off the q.Add call that names the same
// column a few lines above.
func usage(t *testing.T, src, variable string) string {
	t.Helper()
	return section(t, src, "flags.StringArrayVar(&"+variable+",", "`)")
}

func TestCLIEmitsOneCommandPerExposedOperation(t *testing.T) {
	src := generateCLI(t, cliFixture())

	for _, want := range []string{
		"// Code generated by github.com/mind-vm/sqlb. DO NOT EDIT.",
		"package cli",
		"func New(c *client.Client) *cobra.Command {",
		"root.AddCommand(newPostsCommand(c))",
		"root.AddCommand(newOrgsCommand(c))",
		"func newPostsListCommand(c *client.Client) *cobra.Command {",
		"func newPostsGetCommand(c *client.Client) *cobra.Command {",
		"func newPostsCreateCommand(c *client.Client) *cobra.Command {",
		"func newPostsUpdateCommand(c *client.Client) *cobra.Command {",
		"func newPostsDeleteCommand(c *client.Client) *cobra.Command {",
	} {
		if !contains(src, want) {
			t.Errorf("the command tree is missing %q:\n%s", want, src)
		}
	}

	// orgs exposes read and list only. A command for an operation the resource
	// does not serve would be a 405 the CLI could have refused itself.
	for _, forbidden := range []string{
		"func newOrgsCreateCommand", "func newOrgsUpdateCommand", "func newOrgsDeleteCommand",
	} {
		if contains(src, forbidden) {
			t.Errorf("%s should not exist: orgs exposes neither\n%s", forbidden, src)
		}
	}
}

// The flags are the vocabulary. A CLI has no compile step to refuse an illegal
// request at, so a column that did not opt in to a capability must simply have
// no flag that reaches it.
func TestCLIFlagsComeFromCapabilities(t *testing.T) {
	src := generateCLI(t, cliFixture())
	list := section(t, src, "func newPostsListCommand", "\n}\n")

	for _, want := range []string{
		`flags.StringArrayVar(&filterStatus, "status"`,
		`flags.StringArrayVar(&filterOrgID, "org-id"`,
		`flags.StringArrayVar(&filterPublishedAt, "published-at"`,
		`flags.StringVar(&search, "search"`,
		`flags.StringSliceVar(&sort, "sort"`,
		`flags.StringSliceVar(&expand, "expand"`,
	} {
		if !contains(list, want) {
			t.Errorf("list is missing %q:\n%s", want, list)
		}
	}

	// subtitle declares no capability at all, so no flag on this command
	// reaches it. title is Searchable, which implies Filterable, so it does
	// have one — the capability, not the column, is what decides.
	if contains(list, `flags.StringArrayVar(&filterSubtitle`) {
		t.Errorf("a column that did not opt in to filtering has no filter flag:\n%s", list)
	}
	if !contains(list, `flags.StringArrayVar(&filterTitle, "title"`) {
		t.Errorf("Searchable implies Filterable, so title should have a filter flag:\n%s", list)
	}
	// Sorting is the same: status is filterable and not sortable.
	if contains(list, `registerCompletion(cmd, "sort", []string{"title", "-title", "published_at", "-published_at"}`) == false {
		t.Errorf("sort completion should be exactly the sortable columns:\n%s", list)
	}
}

// The operator set is narrowed by column type, exactly as the server narrows
// it: documenting a pattern match on a number would name a request that
// parsing rejects.
func TestCLIFilterUsageNarrowsOperatorsByColumnType(t *testing.T) {
	list := section(t, generateCLI(t, cliFixture()), "func newPostsListCommand", "\n}\n")

	// A bigint gets the comparisons and nothing else.
	viewCount := usage(t, list, "filterViewCount")
	for _, forbidden := range []string{"contains", "ilike", "isnull"} {
		if strings.Contains(viewCount, forbidden) {
			t.Errorf("a non-null number should not offer %q:\n%s", forbidden, viewCount)
		}
	}
	// A nullable timestamp gets the null tests and, being no kind of text, no
	// pattern operators.
	publishedAt := usage(t, list, "filterPublishedAt")
	if !strings.Contains(publishedAt, "isnull, notnull") {
		t.Errorf("a nullable column should offer the null tests:\n%s", publishedAt)
	}
	if strings.Contains(publishedAt, "startswith") {
		t.Errorf("a timestamp should not offer the pattern operators:\n%s", publishedAt)
	}
	// An enum names its values, which is the whole reason for reading --help.
	status := usage(t, list, "filterStatus")
	if !strings.Contains(status, "Values: draft, published.") {
		t.Errorf("an enum filter should name its value set:\n%s", status)
	}
}

// The write bodies carry exactly the columns the REST bodies do, because they
// are the same request and disagreeing would mean a flag the server refuses or
// a column no flag can reach.
func TestCLIWriteFlagsMatchTheRequestBodies(t *testing.T) {
	src := generateCLI(t, cliFixture())

	create := section(t, src, "func newPostsCreateCommand", "\n}\n")
	for _, want := range []string{
		`flags.StringVar(&valTitle, "title"`,
		`flags.StringVar(&valOrgID, "org-id"`, // immutable is settable once, at create
		`flags.StringVar(&valStatus, "status"`,
		`cmd.MarkFlagRequired("title")`,
	} {
		if !contains(create, want) {
			t.Errorf("create is missing %q:\n%s", want, create)
		}
	}
	// A defaulted or nullable column left out means the database's answer, not
	// the zero value, so neither may be required.
	for _, forbidden := range []string{
		`cmd.MarkFlagRequired("status")`,       // has a default
		`cmd.MarkFlagRequired("published-at")`, // nullable
		`&valViewCount`,                        // read-only
		`&valID`,                               // the primary key is not a caller's to set
	} {
		if contains(create, forbidden) {
			t.Errorf("create should not carry %s:\n%s", forbidden, create)
		}
	}

	update := section(t, src, "func newPostsUpdateCommand", "\n}\n")
	if contains(update, `"org-id"`) {
		t.Errorf("an immutable column has no flag on update:\n%s", update)
	}
	if contains(update, `cmd.MarkFlagRequired(`) {
		t.Errorf("every patch flag is optional:\n%s", update)
	}
}

// Presence is read from the flag, not from the value. A flag left out and a
// flag set to "" must send different requests, which is the same distinction
// the generated patch body keeps a presence map for.
func TestCLIWritesOnlyTheFlagsThatWerePassed(t *testing.T) {
	update := section(t, generateCLI(t, cliFixture()), "func newPostsUpdateCommand", "\n}\n")

	if !contains(update, `if cmd.Flags().Changed("title") { body["title"] = valTitle }`) {
		t.Errorf("a patch should send only the flags it was given:\n%s", update)
	}
	// A value flag can say "empty"; it cannot say "null". Each column carries
	// both its spellings, since the flag is written with one and the body key
	// is the other — the same string under this fixture's default WireCase.
	if !contains(update, `setNullFields(body, setNull, []nullableColumn{{"subtitle", "subtitle"}, {"published_at", "published_at"}, {"meta", "meta"}})`) {
		t.Errorf("nullable columns should be reachable through --set-null:\n%s", update)
	}
	if !contains(update, `errors.New("nothing to update: pass at least one field flag")`) {
		t.Errorf("an update naming no column should be refused before the round trip:\n%s", update)
	}
}

// A jsonb column carries a document. Sending the flag's text as a JSON string
// would store the text and succeed, which is worse than failing.
func TestCLISendsJSONColumnsAsDocuments(t *testing.T) {
	create := section(t, generateCLI(t, cliFixture()), "func newPostsCreateCommand", "\n}\n")

	if !contains(create, `if !json.Valid([]byte(valMeta))`) {
		t.Errorf("a jsonb flag should be checked before it is sent:\n%s", create)
	}
	if !contains(create, `body["meta"] = json.RawMessage(valMeta)`) {
		t.Errorf("a jsonb flag should be sent as a document, not as a string:\n%s", create)
	}
}

// The guarantee ADR-0006 makes, in one more place it would be easy to lose: a
// hidden column has no spelling at all — not as a filter, not in the projection
// vocabulary, not as a flag on a write.
func TestCLIHidesHiddenColumnsEverywhere(t *testing.T) {
	src := generateCLI(t, cliFixture())
	if strings.Contains(src, "secret") {
		t.Errorf("a hidden column leaked into the CLI:\n%s", src)
	}
}

func TestCLIPagesByCursorAndNamesItsEnvironment(t *testing.T) {
	src := generateCLI(t, cliFixture())

	// The environment prefix follows the binary name, so two generated CLIs in
	// one shell do not read each other's configuration.
	for _, want := range []string{
		`envOr("BLOGCTL_BASE_URL", "http://localhost:8080")`,
		`os.Getenv("BLOGCTL_TOKEN")`,
		`Use:   "blogctl"`,
	} {
		if !contains(src, want) {
			t.Errorf("the root command is missing %q:\n%s", want, src)
		}
	}

	list := section(t, src, "func newPostsListCommand", "\n}\n")
	if !contains(list, `flags.BoolVar(&all, "all"`) {
		t.Errorf("a resource with a primary key should offer the cursor walk:\n%s", list)
	}
	if !contains(list, `return runRequest(c, cmd, client.Request{Method: http.MethodGet, Path: "/posts", Query: q}, all)`) {
		t.Errorf("--all should reach the walk:\n%s", list)
	}
}

// Cursor paging needs a key to break ties with. A model without one can still
// be listed, so the flag is withheld rather than the command refused — and
// withholding it keeps --help honest, since next_cursor will not be in the
// responses either.
func TestCLIWithholdsTheCursorWalkWithoutAPrimaryKey(t *testing.T) {
	r := schema.NewRegistry()
	r.Table("events",
		schema.Text("name").Filterable(),
		schema.Timestamp("at").Sortable(),
	).Expose(schema.REST{Ops: schema.OpList})

	list := section(t, generateCLI(t, r), "func newEventsListCommand", "\n}\n")
	for _, forbidden := range []string{`"cursor"`, `"all"`} {
		if contains(list, forbidden) {
			t.Errorf("a model with no primary key cannot issue a cursor, so %s should be absent:\n%s", forbidden, list)
		}
	}
	if !contains(list, `Query: q}, false)`) {
		t.Errorf("the walk should be off at the call site too:\n%s", list)
	}
}

// A schema with no REST surface has no commands to offer, and should not
// acquire a file that imports cobra for the sake of an empty tree.
func TestCLIIsNotEmittedForASchemaThatExposesNothing(t *testing.T) {
	r := schema.NewRegistry()
	r.Table("internal_jobs", schema.UUIDv7("id").PrimaryKey(), schema.Text("state"))

	dir := t.TempDir()
	files, err := codegen.Generate(codegen.Options{
		Registry: r, Dir: dir, Package: "gen", CLIDir: "cli",
	})
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	for _, f := range files {
		if filepath.Base(f) == "cli_gen.go" {
			t.Errorf("a schema exposing nothing should emit no CLI, got %s", f)
		}
	}
}

// The package clause is derived from a directory name, so it can fail to be an
// identifier. Refusing here names the option to set; go/format would not, since
// it parses without checking that a package name is one.
func TestCLIRefusesADirectoryThatIsNotAPackageName(t *testing.T) {
	dir := t.TempDir()
	_, err := codegen.Generate(codegen.Options{
		Registry: cliFixture(), Dir: dir, Package: "gen", CLIDir: "internal/api-client",
	})
	if err == nil {
		t.Fatal("a directory that is not a Go identifier should be refused")
	}
	if !strings.Contains(err.Error(), "Options.CLIPackage") {
		t.Errorf("the error should name the option that fixes it, got: %v", err)
	}
}

// Check is what makes the CLI safe to commit: it drifts like every other
// generated file, and a stale command tree describes an API the server no
// longer serves.
func TestCLIIsCoveredByCheck(t *testing.T) {
	dir := t.TempDir()
	opts := codegen.Options{
		Registry: cliFixture(), Dir: dir, Package: "gen",
		CLIDir: "cli", CLIName: "blogctl",
		ClientImportPath: "example.com/app/cli/client",
	}
	if _, err := codegen.Generate(opts); err != nil {
		t.Fatalf("Generate: %v", err)
	}
	stale, err := codegen.Check(opts)
	if err != nil {
		t.Fatalf("Check: %v", err)
	}
	if len(stale) > 0 {
		t.Fatalf("a freshly generated tree should be current, got %v", stale)
	}

	path := filepath.Join(dir, "cli", "cli_gen.go")
	if err := os.WriteFile(path, []byte("package cli\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	stale, err = codegen.Check(opts)
	if err != nil {
		t.Fatalf("Check: %v", err)
	}
	if len(stale) != 1 || !strings.Contains(stale[0], "cli_gen.go") {
		t.Fatalf("an edited CLI should be reported stale, got %v", stale)
	}
}
