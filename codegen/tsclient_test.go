// The TypeScript is part of the committed output, so the staleness gate has to
// see it — otherwise the client silently describes a schema the server no
// longer has.
func TestCheckSeesTheTypeScript(t *testing.T) {
	dir := t.TempDir()
	opts := codegen.Options{Registry: tsFixture(), Dir: dir, Package: "gen", TSDir: "web/api"}
	if _, err := codegen.Generate(opts); err != nil {
		t.Fatal(err)
	}
	if stale, err := codegen.Check(opts); err != nil || len(stale) > 0 {
		t.Fatalf("freshly generated output should be current: %v %v", stale, err)
	}

	path := filepath.Join(dir, "web", "api", "client.gen.ts")
	if err := os.WriteFile(path, []byte("// edited by hand\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	stale, err := codegen.Check(opts)
	if err != nil {
		t.Fatal(err)
	}
	if len(stale) != 1 || !strings.Contains(stale[0], "client.gen.ts") {
		t.Errorf("an edited client should be reported stale, got %v", stale)
	}
}

// section returns the emitted text between two markers, so an assertion about
// one declaration cannot be satisfied by a match somewhere else in the file.
func section(t *testing.T, src, from, to string) string {
	t.Helper()
	start := strings.Index(src, from)
	if start < 0 {
		t.Fatalf("%q not found in:\n%s", from, src)
	}
	rest := src[start:]
	end := strings.Index(rest, to)
	if end < 0 {
		t.Fatalf("%q not found after %q", to, from)
	}
	return rest[:end+len(to)]
}

