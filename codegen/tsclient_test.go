// tsFixture is restFixture plus an expandable reference in both directions, so
// that the emitted client has something to narrow a response by.
func tsFixture() *schema.Registry {
	r := schema.NewRegistry()
	org := r.Table("orgs",
		schema.UUIDv7("id").PrimaryKey(),
		schema.Text("name").Sortable(),
	).Expose(schema.REST{Ops: schema.OpRead | schema.OpList})

	r.Table("posts",
		schema.UUIDv7("id").PrimaryKey(),
		schema.Ref("org", org).OnDelete(schema.Cascade).Immutable().Filterable().
			Expandable().Inverse("posts").InverseExpandable(),
		schema.Text("title").Searchable().Sortable(),
		schema.Enum("status", "draft", "published").Default(schema.Value("draft")).Filterable(),
		schema.BigInt("view_count").ReadOnly().Filterable(),
		schema.Timestamp("published_at").Nullable().Filterable().Sortable(),
		schema.Text("secret").Hidden(),
	).Expose(schema.REST{Ops: schema.CRUD | schema.OpList, MaxPageSize: 50})
	return r
}

// generateTS returns the emitted TypeScript, keyed by file name.
func generateTS(t *testing.T, r *schema.Registry) map[string]string {
	t.Helper()
	dir := t.TempDir()
	files, err := codegen.Generate(codegen.Options{
		Registry: r, Dir: dir, Package: "gen", TSDir: "web/api",
	})
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	out := map[string]string{}
	for _, f := range files {
		if filepath.Ext(f) != ".ts" {
			continue
		}
		b, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		out[filepath.Base(f)] = string(b)
	}
	if len(out) == 0 {
		t.Fatal("no TypeScript was emitted")
	}
	return out
}

func TestTSRowTypesFollowTheWire(t *testing.T) {
	src := generateTS(t, tsFixture())["client.gen.ts"]

	for _, want := range []string{
		"// Code generated by github.com/jryannel/sqlb. DO NOT EDIT.",
		"export interface Post {",
		"id: string;",
		"org_id: string;",                  // snake_case, because that is the wire spelling
		"view_count: number;",              // bigint is a JSON number
		"Values above 2^53 lose precision", // and the loss is silent, so it is stated
		"status: PostStatus;",              // enum keeps its type
		"published_at: string | null;",     // nullable, and a timestamp is a string
		"export type PostStatus = 'draft' | 'published';",
	} {
		if !contains(src, want) {
			t.Errorf("row types missing %q:\n%s", want, src)
		}
	}

	// A hidden column has no spelling here at all: not in the row, not in the
	// projection vocabulary, not as a filter. This is the same guarantee the
	// typed column facade gives Go, carried across the wire.
	for _, forbidden := range []string{"secret"} {
		if contains(src, forbidden) {
			t.Errorf("a hidden column leaked into the client:\n%s", src)
		}
	}
}

func TestTSBodiesOmitWhatAClientMayNotSet(t *testing.T) {
	src := generateTS(t, tsFixture())["client.gen.ts"]

	create := section(t, src, "export interface PostCreate {", "\n}")
	for _, want := range []string{
		"title: string;",                // required
		"status?: PostStatus;",          // defaulted → optional
		"published_at?: string | null;", // nullable → optional, and nullable
	} {
		if !contains(create, want) {
			t.Errorf("create body missing %q:\n%s", want, create)
		}
	}
	// "{ id:" rather than "id:", which org_id would satisfy.
	for _, forbidden := range []string{"{ id:", "view_count", "secret"} {
		if contains(create, forbidden) {
			t.Errorf("create body should not carry %s:\n%s", forbidden, create)
		}
	}

	// An immutable column is settable once, at create, so the patch body has no
	// property for it — the same set the Go patch body uses.
	patch := section(t, src, "export interface PostPatch {", "\n}")
	if contains(patch, "org_id") {
		t.Errorf("an immutable column should be absent from the patch body:\n%s", patch)
	}
	if !contains(patch, "title?: string;") {
		t.Errorf("every patch property is optional:\n%s", patch)
	}
}

// The operator vocabulary per column is the thing an OpenAPI document cannot
// say, and the reason this generator exists rather than openapi-typescript.
func TestTSFilterOperatorsAreNarrowedByColumnType(t *testing.T) {
	src := generateTS(t, tsFixture())["client.gen.ts"]
	where := section(t, src, "export type PostWhere = {", "\n};")

	for _, want := range []string{
		"org_id?: Cond<string>;",     // no pattern operators
		"status?: Cond<PostStatus>;", // an enum compares by equality
		"view_count?: Cond<number>;", // nor on a number
		// A timestamp gets the whole-day operator, and being nullable it gets
		// the null tests too — the extras compose rather than replacing one
		// another (#241).
		"published_at?: Cond<string | Date, DayMatch & NullCheck>;",
	} {
		if !contains(where, want) {
			t.Errorf("filter conditions missing %q:\n%s", want, where)
		}
	}
	// title is Searchable, which implies Filterable, and it is text — so it is
	// the one column that gets the pattern operators.
	if !contains(where, "title?: Cond<string, TextMatch>;") {
		t.Errorf("a text column should offer the pattern operators:\n%s", where)
	}
	// And the day operator is offered to nothing else: it is the one operator
	// whose absence used to be silent, so its presence must not be broad.
	for _, line := range []string{"id?:", "org_id?:", "title?:", "status?:", "view_count?:"} {
		for _, l := range strings.Split(where, "\n") {
			if strings.Contains(l, line) && strings.Contains(l, "DayMatch") {
				t.Errorf("a non-timestamp column offers the day operator:\n%s", l)
			}
		}
	}
}

