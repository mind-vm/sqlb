// Command gen renders the blog schema as the plain `schema.sql` that sqlc
// reads, which is the mechanical half of the sqlb/sqlc pairing story: one
// schema declaration, two consumers.
//
//	go generate ./example/withsqlc/...     regenerate
//	go run ./example/withsqlc/gen -check   fail if the committed output is stale
//
// The -check mode is what makes the claim more than prose. If someone edits
// blogschema and does not regenerate, sqlc is reading a schema the database no
// longer has, and the gate says so.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/mind-vm/sqlb/migrate"
	"github.com/mind-vm/sqlb/schema"

	// Imported for its side effects: declaring a table registers it.
	_ "github.com/mind-vm/sqlb/example/blog/blogschema"
)

const header = `-- Code generated by example/withsqlc/gen. DO NOT EDIT.
--
-- This is the blog schema (example/blog/blogschema) rendered as DDL, and it is
-- the file sqlc reads. sqlb owns the schema; sqlc consumes it. Editing this by
-- hand desynchronises the two, which is why the CI gate regenerates it.
`

func main() {
	check := flag.Bool("check", false, "report a stale schema.sql instead of writing it")
	dir := flag.String("dir", "example/withsqlc", "output directory, relative to the working directory")
	flag.Parse()

	want, err := render()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	path := filepath.Join(*dir, "schema.sql")

	if *check {
		got, err := os.ReadFile(path)
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if string(got) != want {
			fmt.Fprintf(os.Stderr,
				"%s is out of date; run: go generate ./example/withsqlc/...\n", path)
			os.Exit(1)
		}
		fmt.Fprintln(os.Stderr, "schema.sql is current")
		return
	}

	if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// render diffs the declared schema against nothing, which is the DDL that
// creates it.
func render() (string, error) {
	changes, err := migrate.Diff(schema.NewRegistry(), schema.DefaultRegistry())
	if err != nil {
		return "", fmt.Errorf("diffing the blog schema: %w", err)
	}
	if len(changes) == 0 {
		return "", fmt.Errorf("the blog schema produced no DDL, which cannot be right")
	}

	var b strings.Builder
	b.WriteString(header)
	for _, c := range changes {
		up := strings.TrimSpace(c.Up)
		if up == "" {
			continue
		}
		b.WriteString("\n")
		if c.Comment != "" {
			b.WriteString("-- " + c.Comment + "\n")
		}
		b.WriteString(up)
		if !strings.HasSuffix(up, ";") {
			b.WriteString(";")
		}
		b.WriteString("\n")
	}
	return b.String(), nil
}
